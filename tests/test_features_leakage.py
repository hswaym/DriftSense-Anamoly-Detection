"""Comprehensive Phase 5 feature engineering and anti-leakage test suite.

Verifies:
- A5.1 Leakage Invariants:
  1. Perturbation Test: Modifying all data after T leaves features for <= T bit-identical.
  2. Fit-on-train Test: Scaler statistics match train partition only, never val/test or full data.
  3. Label Isolation Test: Ground truth anomaly labels raise immediate ValueError.
  4. Event Timing Test: Events starting at T have zero influence on features at t < T.
  5. Split Ordering Test: Forward-chaining splits with strict non-negative gaps.
  6. Forbidden Column Test: Contemporaneous cost columns (BilledCost, ListCost) never enter feature_names_.
  7. Mode A vs Mode B Test: Mode A excludes contemporaneous usage; Mode B includes ConsumedQuantity_contemporaneous.
  8. Hierarchy & Grain Test: Hourly and daily grains with historical cross-service spend share.
- A5.2 Feature Contract Completeness:
  100% of features generated by FeaturePipeline are documented in docs/v2/feature_contract.md.
"""

from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from driftsense.eval.splits import chronological_split
from driftsense.features.builder import (
    FORBIDDEN_CONTEMPORANEOUS_COST_COLUMNS,
    FeaturePipeline,
)


@pytest.fixture
def panel_fixture() -> pd.DataFrame:
    """Generate a clean synthetic 72-hour panel for 2 services with cost and usage."""
    rows = []
    times = pd.date_range("2024-09-01 00:00:00", periods=72, freq="1h", tz="UTC")
    for svc in ["Compute_EC2", "Storage_S3"]:
        for i, t in enumerate(times):
            base_cost = 25.0 if svc == "Compute_EC2" else 5.0
            base_usage = 100.0 if svc == "Compute_EC2" else 500.0
            rows.append(
                {
                    "ServiceName": svc,
                    "ChargePeriodStart": t,
                    "EffectiveCost": base_cost + float(i % 7),
                    "BilledCost": (base_cost + float(i % 7)) * 1.05,
                    "ListCost": (base_cost + float(i % 7)) * 1.20,
                    "ConsumedQuantity": base_usage + float(i * 3),
                }
            )
    return pd.DataFrame(rows)


def test_a5_1_perturbation_invariance(panel_fixture: pd.DataFrame) -> None:
    """A5.1 Perturbation Test: Modifying all data after T must leave features for <= T bit-identical."""
    df_orig = panel_fixture.copy()
    pipeline = FeaturePipeline(mode="A")

    feats_orig = pipeline.fit_transform(df_orig)

    # Cutoff timestamp T (hour 36)
    cutoff_t = pd.Timestamp("2024-09-02 12:00:00", tz="UTC")

    # Perturb future data (> T)
    df_perturbed = df_orig.copy()
    future_mask = df_perturbed["ChargePeriodStart"] > cutoff_t
    df_perturbed.loc[future_mask, "EffectiveCost"] *= 500.0
    df_perturbed.loc[future_mask, "ConsumedQuantity"] = np.random.RandomState(42).uniform(
        10000, 50000, size=future_mask.sum()
    )

    pipeline_pert = FeaturePipeline(mode="A")
    feats_pert = pipeline_pert.fit_transform(df_perturbed)

    hist_orig = (
        feats_orig[feats_orig["ChargePeriodStart"] <= cutoff_t]
        .sort_values(["ServiceName", "ChargePeriodStart"])
        .reset_index(drop=True)
    )
    hist_pert = (
        feats_pert[feats_pert["ChargePeriodStart"] <= cutoff_t]
        .sort_values(["ServiceName", "ChargePeriodStart"])
        .reset_index(drop=True)
    )

    for col in pipeline.feature_names_:
        pd.testing.assert_series_equal(
            hist_orig[col],
            hist_pert[col],
            obj=f"Perturbation Leakage Violation on feature '{col}' at or before T",
            check_exact=True,
        )


def test_a5_1_fit_on_train_statistics(panel_fixture: pd.DataFrame) -> None:
    """A5.1 Fit-on-Train Test: Scalers expose statistics equal to train slice only."""
    train_df, _, _, _ = chronological_split(
        panel_fixture, train_frac=0.6, val_frac=0.2, test_frac=0.2
    )

    pipeline = FeaturePipeline(mode="A", scale_features=True)
    pipeline.fit(train_df)

    train_stats = pipeline.fit_statistics_
    raw_train_feats = pipeline._generate_raw_features(train_df)

    for col in pipeline.feature_names_:
        col_vals = raw_train_feats[col].dropna()
        if not col_vals.empty:
            expected_mean = float(col_vals.mean())
            actual_mean = train_stats[col]["mean"]
            assert actual_mean == pytest.approx(expected_mean, rel=1e-5), (
                f"Scaler mean for {col} does not match train-slice mean"
            )

    # Prove full data mean differs from train mean due to upward trend
    raw_full_feats = pipeline._generate_raw_features(panel_fixture)
    full_usage_mean = float(raw_full_feats["ConsumedQuantity_lag_1"].dropna().mean())
    train_usage_mean = train_stats["ConsumedQuantity_lag_1"]["mean"]
    assert train_usage_mean < full_usage_mean, "Leakage: Train stats were computed on full data!"


def test_a5_1_label_isolation(panel_fixture: pd.DataFrame) -> None:
    """A5.1 Label Isolation Test: Ground truth anomaly labels raise immediate ValueError."""
    pipeline = FeaturePipeline()

    for forbidden_col in ["is_anomaly", "incident_id", "fault_family", "severity_score"]:
        bad_df = panel_fixture.copy()
        bad_df[forbidden_col] = 1
        with pytest.raises(ValueError, match="LABEL ISOLATION ERROR"):
            pipeline.fit(bad_df)


def test_a5_1_event_timing(panel_fixture: pd.DataFrame) -> None:
    """A5.1 Event Timing Test: Events starting at T have zero influence on features at t < T."""
    event_start_t = pd.Timestamp("2024-09-02 00:00:00", tz="UTC")
    event_end_t = pd.Timestamp("2024-09-02 06:00:00", tz="UTC")

    events_df = pd.DataFrame(
        [
            {
                "service_id": "Compute_EC2",
                "event_type": "DEPLOYMENT",
                "ts_start": event_start_t,
                "ts_end": event_end_t,
            }
        ]
    )

    # Pipeline without events
    pipe_no_ev = FeaturePipeline()
    _ = pipe_no_ev.fit_transform(panel_fixture)

    # Pipeline with events
    pipe_ev = FeaturePipeline()
    feats_ev = pipe_ev.fit_transform(panel_fixture, events_df=events_df)

    # For t < event_start_t, deployment indicator MUST be 0
    pre_event_ev = feats_ev[
        (feats_ev["ServiceName"] == "Compute_EC2")
        & (feats_ev["ChargePeriodStart"] < event_start_t)
    ]
    assert (pre_event_ev["event_active_deployment"] == 0).all()
    assert (pre_event_ev["recent_event_count_24h"] == 0).all()

    # During event window [event_start_t, event_end_t], indicator MUST be 1
    active_mask = (feats_ev["ServiceName"] == "Compute_EC2") & (
        feats_ev["ChargePeriodStart"] >= event_start_t
    ) & (feats_ev["ChargePeriodStart"] <= event_end_t)
    assert (feats_ev.loc[active_mask, "event_active_deployment"] == 1).all()


def test_a5_1_forbidden_cost_columns(panel_fixture: pd.DataFrame) -> None:
    """A5.1 Forbidden Column Test: Contemporaneous cost columns must NEVER enter feature_names_."""
    pipeline = FeaturePipeline()
    pipeline.fit(panel_fixture)

    leaked = FORBIDDEN_CONTEMPORANEOUS_COST_COLUMNS.intersection(pipeline.feature_names_)
    assert not leaked, f"CRITICAL LEAKAGE: Contemporaneous cost columns found in features: {leaked}"


def test_a5_1_mode_a_vs_mode_b(panel_fixture: pd.DataFrame) -> None:
    """A5.1 Mode Distinction Test: Mode A has NO contemporaneous usage; Mode B has ConsumedQuantity_contemporaneous."""
    pipe_a = FeaturePipeline(mode="A").fit(panel_fixture)
    pipe_b = FeaturePipeline(mode="B").fit(panel_fixture)

    # In Mode A, contemporaneous usage is forbidden
    assert "ConsumedQuantity" not in pipe_a.feature_names_
    assert "ConsumedQuantity_contemporaneous" not in pipe_a.feature_names_
    assert "ConsumedQuantity_lag_1" in pipe_a.feature_names_

    # In Mode B, contemporaneous usage is present
    assert "ConsumedQuantity_contemporaneous" in pipe_b.feature_names_
    assert "ConsumedQuantity_lag_1" in pipe_b.feature_names_

    # Verify difference is exactly ConsumedQuantity_contemporaneous
    diff = set(pipe_b.feature_names_) - set(pipe_a.feature_names_)
    assert diff == {"ConsumedQuantity_contemporaneous"}


def test_a5_1_hierarchy_and_grains(panel_fixture: pd.DataFrame) -> None:
    """A5.1 Hierarchy and Multi-Grain Test: Hourly and daily grains with valid spend share."""
    # 1. Hourly grain with hierarchy
    pipe_h = FeaturePipeline(grain="1h", include_hierarchy=True).fit(panel_fixture)
    feats_h = pipe_h.transform(panel_fixture)

    assert "total_spend_lag1" in feats_h.columns
    assert "service_spend_share_lag1" in feats_h.columns
    assert feats_h["service_spend_share_lag1"].between(0.0, 1.0).all()

    # 2. Daily grain roll-up
    pipe_d = FeaturePipeline(grain="1d", cost_lags=(1, 2), cost_windows=(3, 7)).fit(panel_fixture)
    feats_d = pipe_d.transform(panel_fixture)
    # 72 hours = 3 days per service -> 6 total rows
    assert len(feats_d) == 6


def test_a5_2_feature_contract_completeness(panel_fixture: pd.DataFrame) -> None:
    """A5.2 Feature Contract Completeness: 100% of pipeline features are documented in feature_contract.md."""
    contract_path = Path("docs/v2/feature_contract.md")
    assert contract_path.exists(), "docs/v2/feature_contract.md must exist!"

    contract_text = contract_path.read_text(encoding="utf-8")

    # Generate full feature sets for both Mode A and Mode B
    pipe_a = FeaturePipeline(mode="A").fit(panel_fixture)
    pipe_b = FeaturePipeline(mode="B").fit(panel_fixture)

    all_features = set(pipe_a.feature_names_).union(pipe_b.feature_names_)

    # Extract all feature table entries from markdown table: `feature_name`
    documented_features = set(re.findall(r"\|\s*`([a-zA-Z0-9_]+)`\s*\|", contract_text))

    missing = all_features - documented_features
    assert not missing, (
        f"A5.2 CONTRACT INCOMPLETENESS: The following engineered features are missing "
        f"from docs/v2/feature_contract.md: {missing}"
    )
